#!/usr/bin/env python3
"""Generates src/core/CommandNames.inc from the vendored Unity command enums."""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
header = root / "third_party/unity/PhysicsBackend/PhysicsCommands.h"
ext_header = root / "third_party/unity/PhysicsBackend/PhysXPhysicsExtensionCommands.h"
out = root / "src/core/CommandNames.inc"


def enum_names(text, enum_name):
	m = re.search(r"enum class " + enum_name + r"\s*:\s*uint32_t\s*\{(.*?)\};", text, re.S)
	if m is None:
		sys.exit("enum not found: " + enum_name)
	names = []
	for line in m.group(1).splitlines():
		line = line.split("//")[0].strip().rstrip(",")
		if line and line != "Count":
			names.append(line.split("=")[0].strip())
	return names


text = header.read_text()
ext_text = ext_header.read_text()
lines = ["// Generated by scripts/gen-command-names.py. Do not edit.", ""]
for cat in ["SDK", "World", "Body", "Shape", "Query", "Joint", "Articulation"]:
	lines.append("const char* const k%sNames[] = {" % cat)
	lines += ['\t"%s",' % n for n in enum_names(text, cat)]
	lines += ["};", ""]
lines.append("const char* const kPhysXExtensionNames[] = {")
lines += ['\t"%s",' % n for n in enum_names(ext_text, "PhysXExtension")]
lines += ["};", ""]
out.write_text("\n".join(lines))
print("wrote", out)
